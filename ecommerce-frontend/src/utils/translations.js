export const useTranslation = (language = 'en') => {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
  return (key, params = {}) => {
    let text = dict[key] || TRANSLATIONS.en[key] || key;
    Object.keys(params).forEach((p) => {
      text = text.replace(`{{${p}}}`, params[p]);
    });
    return text;
  };
};
